import prisma from "@/db/prisma";
import { Prisma } from "@prisma/client";
import { computeM4Baseline } from "./baseline-m4";
import { type BankTxForBaseline, type RecurringPatternForBaseline } from "./baseline";

export async function generateShadowEvaluation(checkpointId: string, companyId: string, tx: Prisma.TransactionClient = prisma) {
    const checkpoint = await tx.forecastCheckpoint.findUnique({
        where: { id: checkpointId },
        include: { cashSnapshot: true }
    });

    if (!checkpoint) {
        throw new Error(`Checkpoint ${checkpointId} not found`);
    }

    // 1. Get the 13-week M1 arrays from the checkpoint's breakdownJson
    const m1Breakdown = checkpoint.breakdownJson ? JSON.parse(checkpoint.breakdownJson) : null;
    let m1RawBaselineInflow = new Array(13).fill(0);
    let m1ExplicitDeductionInflow = new Array(13).fill(0);
    let m1PreAiResidualInflow = new Array(13).fill(0);
    let m1AiFactorInflow = new Array(13).fill(1);
    let m1PostAiResidualInflow = new Array(13).fill(0);

    let m1RawBaselineOutflow = new Array(13).fill(0);
    let m1ExplicitDeductionOutflow = new Array(13).fill(0);
    let m1PreAiResidualOutflow = new Array(13).fill(0);
    let m1AiFactorOutflow = new Array(13).fill(1);
    let m1PostAiResidualOutflow = new Array(13).fill(0);
    
    // We expect the breakdownJson to be an array of weeks from forecast.ts
    // In cash-checkin, the breakdownJson is the full week array or just one week?
    // cash-checkin does:
    // const parsedBreakdown = JSON.parse(finalBreakdownJson);
    // const targetWeek = parsedBreakdown;
    // Wait, the checkpoint breakdownJson is typically the *target week* only or the full array?
    // Oh, the full array is typically generated by generateForecastWeeks.
    
    if (m1Breakdown && Array.isArray(m1Breakdown.weeks)) {
        m1Breakdown.weeks.forEach((week: any, w: number) => {
            if (w >= 13) return;
            const inBase = (week.breakdown.inflows || []).find((i: any) => i.sourceType === "baseline");
            if (inBase && inBase.metadata) {
                m1RawBaselineInflow[w] = inBase.metadata.stage1Raw || 0;
                m1ExplicitDeductionInflow[w] = inBase.metadata.explicitDeduction || 0;
                m1PreAiResidualInflow[w] = inBase.metadata.stage2PreAi || 0;
                m1AiFactorInflow[w] = inBase.metadata.aiFactor || 1;
                m1PostAiResidualInflow[w] = inBase.amount || 0;
            }

            const outBase = (week.breakdown.outflows || []).find((o: any) => o.sourceType === "baseline");
            if (outBase && outBase.metadata) {
                m1RawBaselineOutflow[w] = outBase.metadata.stage1Raw || 0;
                m1ExplicitDeductionOutflow[w] = outBase.metadata.explicitDeduction || 0;
                m1PreAiResidualOutflow[w] = outBase.metadata.stage2PreAi || 0;
                m1AiFactorOutflow[w] = outBase.metadata.aiFactor || 1;
                m1PostAiResidualOutflow[w] = outBase.amount || 0;
            }
        });
    }

    // 2. Fetch required inputs to re-run preprocessing and M4
    const [
        bankTxs,
        recurringPatternsRaw,
        cashSnapshot
    ] = await Promise.all([
        tx.bankTransaction.findMany({
            where: {
                companyId,
                txDate: { gte: new Date(Date.now() - 365 * 86_400_000) },
            },
            select: { amount: true, txDate: true, description: true, direction: true },
        }),
        tx.recurringPattern.findMany({ where: { companyId } }),
        tx.cashSnapshot.findUnique({ where: { id: checkpoint.cashSnapshotId } })
    ]);

    if (!cashSnapshot) throw new Error("Cash snapshot missing");

    const bankTxsForBaseline = bankTxs.map(tx => ({
        amount: tx.direction === "inflow" ? tx.amount : -tx.amount,
        date: tx.txDate,
        merchantKey: tx.description ?? "",
    }));

    const patternsForBaseline = recurringPatternsRaw.map(rp => ({
        merchantKey: rp.merchantKey ?? rp.displayName,
        direction: rp.direction,
        category: rp.category,
        isIncluded: rp.isIncluded,
        typicalAmount: rp.typicalAmount,
        amountStdDev: rp.amountStdDev,
        cadence: rp.cadence as any,
    }));

    // Re-run M4 logic
    const m4Baseline = computeM4Baseline(bankTxsForBaseline, patternsForBaseline, cashSnapshot.asOfDate);
    
    // Assemble inputs for M4 Forecast (we skip full AI orchestration for M4 shadow evaluation to save cycles, 
    // we only need the baseline performance pre-AI)

    // 3. Save BaselineSnapshotHistory
    await tx.baselineSnapshotHistory.upsert({
        where: { forecastCheckpointId: checkpointId },
        update: {
            m1RawBaselineJson: JSON.stringify({ inflow: m1RawBaselineInflow, outflow: m1RawBaselineOutflow }),
            m1ExplicitDeductionJson: JSON.stringify({ inflow: m1ExplicitDeductionInflow, outflow: m1ExplicitDeductionOutflow }),
            m1PreAiResidualJson: JSON.stringify({ inflow: m1PreAiResidualInflow, outflow: m1PreAiResidualOutflow }),
            m1AiFactorJson: JSON.stringify({ inflow: m1AiFactorInflow, outflow: m1AiFactorOutflow }),
            m1PostAiResidualJson: JSON.stringify({ inflow: m1PostAiResidualInflow, outflow: m1PostAiResidualOutflow }),
            
            m4RawBaselineJson: JSON.stringify({
                inflow: new Array(13).fill(m4Baseline.variableInflowWeekly),
                outflow: new Array(13).fill(m4Baseline.variableOutflowWeekly)
            }),
        },
        create: {
            id: require("crypto").randomUUID(),
            forecastCheckpointId: checkpointId,
            companyId,
            asOfDate: cashSnapshot.asOfDate,
            variableInflowWeekly: m4Baseline.variableInflowWeekly,
            variableOutflowWeekly: m4Baseline.variableOutflowWeekly,
            
            explicitInflowJson: "{}",
            explicitOutflowJson: "{}",
            evidenceStateJson: "{}",
            
            promptVersionHash: "v1-m4-shadow",
            modelIdentifier: "shadow-m4",
            
            rawAiResponseJson: "{}",
            reasoningLog: "Shadow M4 evaluation run",
            
            m1RawBaselineJson: JSON.stringify({ inflow: m1RawBaselineInflow, outflow: m1RawBaselineOutflow }),
            m1ExplicitDeductionJson: JSON.stringify({ inflow: m1ExplicitDeductionInflow, outflow: m1ExplicitDeductionOutflow }),
            m1PreAiResidualJson: JSON.stringify({ inflow: m1PreAiResidualInflow, outflow: m1PreAiResidualOutflow }),
            m1AiFactorJson: JSON.stringify({ inflow: m1AiFactorInflow, outflow: m1AiFactorOutflow }),
            m1PostAiResidualJson: JSON.stringify({ inflow: m1PostAiResidualInflow, outflow: m1PostAiResidualOutflow }),
            
            m4RawBaselineJson: JSON.stringify({
                inflow: new Array(13).fill(m4Baseline.variableInflowWeekly),
                outflow: new Array(13).fill(m4Baseline.variableOutflowWeekly)
            }),
        }
    });

    console.log(`[Shadow Orchestrator] Generated shadow evaluation for Checkpoint ${checkpointId}`);
}
